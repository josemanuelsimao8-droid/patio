const languageKey = 'patio-language';
let currentLanguage = 'pt';
const originalTexts = new WeakMap();
const originalAttributes = new WeakMap();
const originalMetaContent = new WeakMap();
const originalTitle = { source: document.title, last: document.title };

function translated(value, language = currentLanguage) {
	if (language !== 'en') return value;
	if (en[value]) return en[value];
	const photoMatch = value.match(/^Ver fotografia (de prato )?(\d+) de (.+)$/);
	if (photoMatch) return `View ${photoMatch[1] ? 'dish ' : ''}photo ${photoMatch[2]} of ${photoMatch[3]}`;
	const photoCaption = value.match(/^Fotografia do (.+), fotografia (\d+)$/);
	if (photoCaption) return `Photo ${photoCaption[2]} of ${photoCaption[1]}`;
	return value.replace(/fotografias/g, 'photos').replace(/fotografia/g, 'photo');
}

function translateTextNode(node) {
	if (node.parentElement?.closest('.lang-btn, .lang-menu')) return;
	let state = originalTexts.get(node);
	if (!state || node.nodeValue !== state.last) {
		state = { source: node.nodeValue, last: node.nodeValue };
		originalTexts.set(node, state);
	}
	const leading = state.source.match(/^\s*/)?.[0] || '';
	const trailing = state.source.match(/\s*$/)?.[0] || '';
	const content = state.source.slice(leading.length, state.source.length - trailing.length || undefined);
	const normalized = content.replace(/\s+/g, ' ').trim();
	if (!normalized) return;
	const next = currentLanguage === 'en' ? `${leading}${translated(normalized, 'en')}${trailing}` : state.source;
	if (node.nodeValue !== next) node.nodeValue = next;
	state.last = next;
}

function translateAttribute(element, attribute) {
	const value = element.getAttribute(attribute);
	if (value === null) return;
	let attributes = originalAttributes.get(element);
	if (!attributes) {
		attributes = new Map();
		originalAttributes.set(element, attributes);
	}
	let state = attributes.get(attribute);
	if (!state || value !== state.last) {
		state = { source: value, last: value };
		attributes.set(attribute, state);
	}
	const next = currentLanguage === 'en' ? translated(state.source, 'en') : state.source;
	if (next !== value) element.setAttribute(attribute, next);
	state.last = next;
}

function translateElement(element) {
	const elements = [element, ...element.querySelectorAll('*')];
	for (const current of elements) {
		for (const attribute of ['alt', 'aria-label', 'aria-description', 'placeholder', 'title', 'value', 'content', 'data-caption']) {
			translateAttribute(current, attribute);
		}
	}
	const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
	while (walker.nextNode()) {
		if (!walker.currentNode.parentElement.closest('script, style, noscript')) translateTextNode(walker.currentNode);
	}
}

function setLanguage(language) {
	currentLanguage = language === 'en' ? 'en' : 'pt';
	try {
		localStorage.setItem(languageKey, currentLanguage);
	} catch {}
	document.documentElement.lang = currentLanguage === 'en' ? 'en' : 'pt-PT';
	if (document.title !== originalTitle.last) originalTitle.source = document.title;
	const nextTitle = currentLanguage === 'en' ? translated(originalTitle.source, 'en') : originalTitle.source;
	if (document.title !== nextTitle) document.title = nextTitle;
	originalTitle.last = nextTitle;
	document.querySelectorAll('meta[content]').forEach((meta) => {
		if (meta.closest('head')) translateAttribute(meta, 'content');
	});
	translateElement(document.body);
	document.querySelectorAll('.lang-btn').forEach((button) => {
		const label = button.firstChild;
		if (label?.nodeType === Node.TEXT_NODE) label.nodeValue = `${currentLanguage.toUpperCase()} `;
		button.setAttribute('aria-label', currentLanguage === 'en' ? 'Choose language' : 'Escolher idioma');
		button.setAttribute('aria-expanded', 'false');
		button.closest('.lang')?.classList.remove('open');
	});
	document.querySelectorAll('.lang-menu button').forEach((button) => {
		button.setAttribute('aria-selected', String(button.textContent.trim().toLowerCase() === currentLanguage));
	});
}

document.addEventListener('click', (event) => {
	const option = event.target.closest('.lang-menu button');
	if (option) setLanguage(option.textContent.trim().toLowerCase());
});

const observer = new MutationObserver((mutations) => {
	for (const mutation of mutations) {
		if (mutation.type === 'characterData') translateTextNode(mutation.target);
		if (mutation.type === 'attributes') translateElement(mutation.target);
		mutation.addedNodes?.forEach((node) => {
			if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
			else if (node.nodeType === Node.ELEMENT_NODE && !node.matches('script, style, noscript')) translateElement(node);
		});
	}
});
observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['alt', 'aria-label', 'aria-description', 'placeholder', 'title', 'value', 'content', 'data-caption'] });

